// Writes public/_redirects from lib/legacy-redirects.json before each build.
// Netlify applies these at the edge, before Next.js, and matches paths with or
// without a trailing slash, so an old URL like /services/seo-company-chandigarh/
// resolves in one hop. (Next.js strips the slash first, costing a second hop.)
// next.config.ts keeps the same rules as a fallback for local dev.
import { readFileSync, writeFileSync } from "node:fs";

const rules = JSON.parse(readFileSync(new URL("../lib/legacy-redirects.json", import.meta.url), "utf8"));
const toNetlify = (path) => path.replace(/\/:[a-zA-Z]+\*$/, "/*");
const lines = rules.map((r) => `${toNetlify(r.source)}  ${r.destination}  ${r.permanent ? 301 : 302}`);
writeFileSync(
  new URL("../public/_redirects", import.meta.url),
  `# Generated by scripts/gen-netlify-redirects.mjs from lib/legacy-redirects.json. Do not edit.\n${lines.join("\n")}\n`,
);
console.log(`_redirects: ${lines.length} rules`);
